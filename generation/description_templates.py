def parse_feature_entries(important_features: list[str]) -> Dict[str, list[tuple[str, str]]]:
    """Parse 'feature:value' strings into grouped {category: [(name, clinical_text)]} dict."""
    from analysis.feature_metadata import FEATURE_METADATA

    grouped: Dict[str, list[tuple[str, str]]] = {category: [] for category in CATEGORY_ORDER}
    for entry in important_features:
        parts = entry.split(":", 1)
        feature_key = parts[0]
        label_value = parts[1] if len(parts) > 1 else ""

        desc_entry = LABEL_DESCRIPTIONS.get(feature_key)
        if desc_entry:
            category, rus_name, value_map = desc_entry
            clinical_text = value_map.get(label_value, label_value)
            grouped.setdefault(category, []).append((rus_name, clinical_text))
            continue

        routing = FEATURE_METADATA.get(feature_key)
        rus_name = routing[1] if routing else feature_key
        fallback_category = "цвет" if "color" in feature_key or "delta" in feature_key else "текстура"
        grouped.setdefault(fallback_category, []).append((rus_name, label_value))
    return grouped


def format_grouped_features(grouped: Dict[str, list[tuple[str, str]]]) -> str:
    """Format grouped features into structured text for the prompt."""
    sections: list[str] = []
    for category in CATEGORY_ORDER:
        items = grouped.get(category, [])
        if not items:
            continue
        title = CATEGORY_TITLES.get(category, category.upper())
        lines = [f"- {name}: {text}" for name, text in items]
        sections.append(f"{title}:\n" + "\n".join(lines))
    return "\n\n".join(sections)


def format_classification(classification: ClassificationResult) -> str:
    """Format classification block for the prompt."""
    lines = ["КЛАССИФИКАЦИЯ ОБРАЗОВАНИЯ:"]
    lines.extend(classification.iter_prompt_lines())
    return "\n".join(lines)


def build_messages(
    grouped_features: Dict[str, list[tuple[str, str]]],
    classification: ClassificationResult | None,
) -> list[dict[str, str]]:
    messages: list[dict[str, str]] = [{"role": "system", "content": SYSTEM_PROMPT}]
    for example in FEW_SHOT_EXAMPLES:
        user_text = f"Составь клиническое дерматоскопическое описание по следующим данным:\n\n{example['features']}"
        if example.get("classification"):
            user_text += f"\n\n{example['classification']}"
        messages.append({"role": "user", "content": user_text})
        messages.append({"role": "assistant", "content": str(example["output"])})

    features_text = format_grouped_features(grouped_features)
    classification_block = f"\n\n{format_classification(classification)}" if classification is not None else ""
    messages.append(
        {
            "role": "user",
            "content": (
                "Составь клиническое дерматоскопическое описание по следующим данным:\n\n"
                f"{features_text}{classification_block}"
            ),
        }
    )
    return messages
