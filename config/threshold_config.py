def apply_threshold(
    value: Optional[float],
    thresholds: ThresholdList,
    default: Optional[str] = None,
) -> Optional[str]:
    """
    Универсальное применение порогов: возвращает метку для первого интервала [low, high),
    в который попадает value. Если value is None или не попадает ни в один интервал — возвращает default.
    """
    if value is None:
        return default
    for low, high, label in thresholds:
        if low <= value < high:
            return label
    return default
